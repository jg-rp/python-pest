def generate() -> str:
    constants: list[str] = []
    names: list[str] = []
    literals: list[str] = []
    mapping: list[str] = []

    for id_, (name, desc) in enumerate(TOKEN_DEFINITIONS.items(), 1):
        constant = f"TOKEN_{name}"

        constants.append(f"{constant}: Literal[{id_}] = {id_}")
        names.append(f"    {constant!r}: {desc!r}")
        literals.append(f"    {id_}")
        mapping.append(f"    {constant}: {json.dumps(constant)}")

    return f"""\
# DO NOT EDIT -- generated by generate_tokens.py

from typing import Literal

__all__ = (
{",\n".join(f'    "TOKEN_{name}"' for name in TOKEN_DEFINITIONS)},
)

type TokenKind = Literal[\n{",\n".join(literals)},\n]

type Token = tuple[TokenKind, int, int]
\"\"\"Token type, start index and end index.\"\"\"

{chr(10).join(constants)}

TOKEN_NAMES = (
    None,
{chr(10).join(f"    {json.dumps(desc)}," for desc in TOKEN_DEFINITIONS.values())}
)

TOKEN_MAP = {{
{",\n".join(mapping)},
}}


def token_value(token: Token, source: str) -> str:
    \"\"\"Return the substring in source spanned by token.\"\"\"
    return source[token[1] : token[2]]


def span(start: Token, stop: Token) -> Token:
    \"\"\"Return a new token spanning start and stop.\"\"\"
    return (TOKEN_SPAN, start[1], stop[2])


def token_position(token: Token, source: str) -> tuple[int, int]:
    \"\"\"Return the line and column number in `source` pointed to by `token`.\"\"\"
    line_number = source.count("\\n", 0, token[1]) + 1
    column_number = token[1] - source.rfind("\\n", 0, token[1])
    return (line_number, column_number - 1)
"""


if __name__ == "__main__":
    print(generate(), end="")  # noqa: T201
